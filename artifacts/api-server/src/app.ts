import express, { type Express } from "express";
import cors from "cors";
import pinoHttp from "pino-http";
import router from "./routes";
import { logger } from "./lib/logger";

const app: Express = express();

// We sit behind Replit's reverse proxy. Trust it so req.ip reflects
// the real client IP (X-Forwarded-For), making per-IP rate limiting
// meaningful instead of collapsing every caller onto the proxy IP.
app.set("trust proxy", true);

app.use(
  pinoHttp({
    logger,
    serializers: {
      req(req) {
        return {
          id: req.id,
          method: req.method,
          url: req.url?.split("?")[0],
        };
      },
      res(res) {
        return {
          statusCode: res.statusCode,
        };
      },
    },
  }),
);
app.use(cors());
// Allow base64-encoded images (1024x1024 JPEG/PNG can land near
// a few hundred KB once base64-expanded), so bump the JSON limit.
app.use(express.json({ limit: "15mb" }));
app.use(express.urlencoded({ extended: true, limit: "15mb" }));

app.use("/api", router);

export default app;
